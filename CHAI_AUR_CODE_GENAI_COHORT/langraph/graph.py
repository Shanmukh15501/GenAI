import os
from dotenv import load_dotenv
from openai import OpenAI
from langgraph.graph import StateGraph, START, END
from typing_extensions import TypedDict

load_dotenv()

client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))


class State(TypedDict):
    """Represents the state passed between nodes in the LangGraph pipeline.

    Attributes:
        query: The user's input question or message.
        llm_result: The response generated by the LLM.
    """
    query: str
    llm_result: str


def chatbot(state: State) -> dict:
    """LangGraph node that sends the user query to OpenAI and returns the response.

    Args:
        state: Current graph state containing the user's query.

    Returns:
        A dict with 'llm_result' set to the model's reply.
    """
    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[{"role": "user", "content": state["query"]}]
    )
    return {"llm_result": response.choices[0].message.content}


graph_builder = StateGraph(State)
graph_builder.add_node("chatbot", chatbot)
graph_builder.add_edge(START, "chatbot")
graph_builder.add_edge("chatbot", END)

graph = graph_builder.compile()


def chat():
    """Runs an interactive command-line chat loop.

    Reads user input, passes it through the LangGraph pipeline,
    and prints the LLM's response. Type 'exit' or 'quit' to stop.
    """
    print("Chatbot ready! Type 'exit' to quit.\n")
    while True:
        user_input = input("You: ").strip()
        if user_input.lower() in ("exit", "quit"):
            break
        if not user_input:
            continue

        result = graph.invoke({"query": user_input})
        print(f"AI: {result['llm_result']}\n")


if __name__ == "__main__":
    chat()
