# flake8: noqa

from typing_extensions import TypedDict
from openai import OpenAI
from typing import Literal
from dotenv import load_dotenv
from langgraph.graph import StateGraph, START, END
from pydantic import BaseModel

load_dotenv()
client = OpenAI()


class ClassifyIntentResponse(BaseModel):
    """Structured output for intent classification."""
    is_coding_question: bool


class AccuracyEvaluationResponse(BaseModel):
    """Structured output for accuracy evaluation of a coding answer."""
    accuracy_percentage: str


class State(TypedDict):
    """Represents the state passed between nodes in the LangGraph pipeline.

    Attributes:
        user_query: The user's input question or message.
        llm_result: The response generated by the LLM.
        accuracy_percentage: Accuracy score of the coding answer (0-100).
        is_coding_question: Whether the user's query is a coding-related question.
    """
    user_query: str
    llm_result: str | None
    accuracy_percentage: str | None
    is_coding_question: bool | None


def detect_intent(state: State):
    """Detects whether the user's query is a coding question.

    Uses OpenAI structured output (Pydantic) to return a strict true/false result.

    Args:
        state: Current graph state containing the user's query.

    Returns:
        Updated state with 'is_coding_question' set to True or False.
    """
    print("⚠️ detect_intent")
    query = state["user_query"]

    SYSTEM_PROMPT = """
    You are an AI assistant. Your job is to detect if the user's query is
    related to coding question or not.
    Return the response in specified JSON boolean only.
    """

    response = client.beta.chat.completions.parse(
        model="gpt-4o-mini",
        response_format=ClassifyIntentResponse,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": query},
        ]
    )

    is_coding_question = response.choices[0].message.parsed.is_coding_question
    state["is_coding_question"] = is_coding_question

    return state


def route_intent(state: State) -> Literal["handle_general", "handle_coding"]:
    """Routes the query to the appropriate handler based on detected intent.

    Args:
        state: Current graph state with is_coding_question set.

    Returns:
        Name of the next node — 'handle_coding' or 'handle_general'.
    """
    print("⚠️ route_intent")
    if state["is_coding_question"]:
        return "handle_coding"
    return "handle_general"


def handle_general(state: State):
    """Handles general (non-coding) questions using gpt-4o-mini.

    Args:
        state: Current graph state containing the user's query.

    Returns:
        Updated state with 'llm_result' containing the answer.
    """
    print("⚠️ handle_general")
    query = state["user_query"]

    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[
            {"role": "user", "content": query}
        ]
    )

    state["llm_result"] = response.choices[0].message.content

    return state


def handle_coding(state: State):
    """Handles coding-related questions using gpt-4o as a coding expert.

    Args:
        state: Current graph state containing the user's query.

    Returns:
        Updated state with 'llm_result' containing the coding answer.
    """
    print("⚠️ handle_coding")
    query = state["user_query"]

    SYSTEM_PROMPT = """
        You are a Coding Expert Agent
    """

    response = client.chat.completions.create(
        model="gpt-4o",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": query}
        ]
    )

    state["llm_result"] = response.choices[0].message.content

    return state


def evaluate_accuracy(state: State):
    """Evaluates the accuracy of the coding answer against the original question.

    Uses OpenAI structured output to return an accuracy percentage.

    Args:
        state: Current graph state containing the query and llm_result.

    Returns:
        Updated state with 'accuracy_percentage' set.
    """
    print("⚠️ evaluate_accuracy")
    query = state["user_query"]
    llm_code = state["llm_result"]

    SYSTEM_PROMPT = f"""
        You are expert in calculating accuracy of the code according to the question.
        Return the percentage of accuracy

        User Query: {query}
        Code: {llm_code}
    """

    response = client.beta.chat.completions.parse(
        model="gpt-4o",
        response_format=AccuracyEvaluationResponse,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": query},
        ]
    )

    state["accuracy_percentage"] = response.choices[0].message.parsed.accuracy_percentage
    return state


def should_retry(state: State) -> Literal["handle_coding", "__end__"]:
    """Decides whether to retry coding if accuracy is below 99%.

    Args:
        state: Current graph state with accuracy_percentage set.

    Returns:
        'handle_coding' to retry, or '__end__' if accuracy is sufficient.
    """
    accuracy = float(state["accuracy_percentage"].strip().rstrip("%"))
    if accuracy < 99:
        return "handle_coding"
    return "__end__"


graph_builder = StateGraph(State)

# Define Nodes
graph_builder.add_node("detect_intent", detect_intent)
graph_builder.add_node("handle_general", handle_general)
graph_builder.add_node("handle_coding", handle_coding)
graph_builder.add_node("evaluate_accuracy", evaluate_accuracy)

graph_builder.add_edge(START, "detect_intent")
graph_builder.add_conditional_edges("detect_intent", route_intent)

graph_builder.add_edge("handle_general", END)

graph_builder.add_edge("handle_coding", "evaluate_accuracy")
graph_builder.add_conditional_edges("evaluate_accuracy", should_retry)

graph = graph_builder.compile()


def main():
    """Entry point — reads user input, runs the graph, and streams events."""
    user = input("> ")

    _state: State = {
        "user_query": user,
        "accuracy_percentage": None,
        "is_coding_question": False,
        "llm_result": None
    }

    for event in graph.stream(_state):
        print("Event", event)


if __name__ == "__main__":
    main()
